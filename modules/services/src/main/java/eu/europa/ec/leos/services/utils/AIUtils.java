    private void appendValueNewColumn(Node node, String value) {
        Node tdElt = node.getOwnerDocument().createElement(XmlHelper.TD);
        XercesUtils.addAttribute(tdElt, XMLID, IdGenerator.generateId());
        Node pElt = node.getOwnerDocument().createElement(XmlHelper.P);
        XercesUtils.addAttribute(pElt, XMLID, IdGenerator.generateId());
        if (StringUtils.isNotBlank(value)) {
            appendValueIns(pElt, value);
        } else {
            pElt.setTextContent(" ");
        }
        tdElt.appendChild(pElt);
        node.appendChild(tdElt);
    }

    private void appendValuesNewColumn(Node node, List<String> values) {
        Node tdElt = node.getOwnerDocument().createElement(XmlHelper.TD);
        XercesUtils.addAttribute(tdElt, XMLID, IdGenerator.generateId());
        Node pElt = node.getOwnerDocument().createElement(XmlHelper.P);
        XercesUtils.addAttribute(pElt, XMLID, IdGenerator.generateId());
        if (!values.isEmpty()) {
            appendValueIns(pElt, String.join(", ", values));
        } else {
            pElt.setTextContent(" ");
        }
        tdElt.appendChild(pElt);
        node.appendChild(tdElt);
    }

    private void appendRefsInNewColumn(Node node, List<String> referenceIds, Bill bill, String lfdsRef) {
        Node tdElt = node.getOwnerDocument().createElement(XmlHelper.TD);
        XercesUtils.addAttribute(tdElt, XMLID, IdGenerator.generateId());
        Node pElt = node.getOwnerDocument().createElement(XmlHelper.P);
        XercesUtils.addAttribute(pElt, XMLID, IdGenerator.generateId());
        appendRefsIns(pElt, referenceIds, bill, lfdsRef);
        tdElt.appendChild(pElt);
        node.appendChild(tdElt);
    }

    private void appendValueIns(Node node, String value) {
        Node insElt = node.getOwnerDocument().createElement(LEOS_TC_INSERT_ELEMENT_NAME);
        XercesUtils.addAttribute(insElt, XMLID, IdGenerator.generateId());
        XercesUtils.addAttribute(insElt, LEOS_UID, AI_USER);
        XercesUtils.addAttribute(insElt, LEOS_TITLE, "Generated by AI : " + LocalDateTime.now().toString());
        insElt.setTextContent(value);
        if (isBlank(node)) {
            node.setTextContent("");
        }
        node.appendChild(insElt);
    }

    private void appendValuesIns(Node node, List<String> values) {
        for (int i=0; i< values.size(); i++) {
            String value = values.get(i);
            if (i>0) {
                Node seperatorNode = node.getOwnerDocument().createTextNode(", ");
                node.appendChild(seperatorNode);
            }
            Node insElt = node.getOwnerDocument().createElement(LEOS_TC_INSERT_ELEMENT_NAME);
            XercesUtils.addAttribute(insElt, XMLID, IdGenerator.generateId());
            XercesUtils.addAttribute(insElt, LEOS_UID, AI_USER);
            XercesUtils.addAttribute(insElt, LEOS_TITLE, "Generated by AI : " + LocalDateTime.now().toString());
            insElt.setTextContent(value);
            if (isBlank(node)) {
                node.setTextContent("");
            }
            node.appendChild(insElt);
        }
    }

    private void appendRefsIns(Node node, List<String> referenceIds, Bill bill, String lfdsRef) {
        for (int i=0; i< referenceIds.size(); i++) {
            String id = referenceIds.get(i);
            if (i>0) {
                Node seperatorNode = node.getOwnerDocument().createTextNode(", ");
                node.appendChild(seperatorNode);
            }
            Node insElt = node.getOwnerDocument().createElement(LEOS_TC_INSERT_ELEMENT_NAME);
            XercesUtils.addAttribute(insElt, XMLID, IdGenerator.generateId());
            XercesUtils.addAttribute(insElt, LEOS_UID, AI_USER);
            XercesUtils.addAttribute(insElt, LEOS_TITLE, "Generated by AI : " + LocalDateTime.now().toString());
            appendNodeMref(insElt, bill.getMetadata().get().getRef(), id, lfdsRef);
            if (isBlank(node)) {
                node.setTextContent("");
            }
            node.appendChild(insElt);
        }
    }

    private void insertValueInNthColumn(Node row, NodeList columns, int n, String value) {
        if (value == null) {
            return;
        }
        if (columns.getLength() > n) {
            if (StringUtils.isNotBlank(value)) {
                appendValueIns(XercesUtils.getFirstChild(columns.item(n)), value);
            }
        } else {
            appendValueNewColumn(row, value);
        }
    }

    private void insertValuesInNthColumn(Node row, NodeList columns, int n, List<String> values) {
        if (values == null || values.isEmpty()) {
            return;
        }
        if (columns.getLength() > n) {
            appendValuesIns(XercesUtils.getFirstChild(columns.item(n)), values);
        } else {
            appendValuesNewColumn(row, values);
        }
    }

    private void insertIdsInNthColumn(Node row, NodeList columns, int n, List<String> referenceIds, Bill bill, String lfdsRef) {
        if (referenceIds == null || referenceIds.isEmpty()) {
            return;
        }
        if (columns.getLength() > n) {
            appendRefsIns(XercesUtils.getFirstChild(columns.item(n)), referenceIds, bill, lfdsRef);
        } else {
            appendRefsInNewColumn(row, referenceIds, bill, lfdsRef);
        }
    }

    // Checks if a row or a column is empty
    private boolean isBlank(Node node) {
        return StringUtils.isBlank(node.getTextContent().replaceAll("[\\n|\\s|\\u00A0]", ""));
    }

    // Checks if a row or a column is not empty
    private boolean isNotBlank(Node node) {
        return StringUtils.isNotBlank(node.getTextContent().replaceAll("[\\n|\\s|\\u00A0]", ""));
    }

    private boolean doesContainsValue(Node node, String value) {
        return value == null || node.getTextContent().toLowerCase().contains(value.toLowerCase());
    }

    private boolean doesContainsValues(Node node, List<String> values) {
        for (String value : values) {
            if (value != null && !node.getTextContent().toLowerCase().contains(value.toLowerCase())) {
                return false;
            }
        }
        return true;
    }

    private boolean doesContainsRefs(Node node, List<String> ids, Bill bill) {
        for (String id : ids) {
            final String value = referenceLabelService.generateLabelStringRef(Arrays.asList(id),
                    bill.getMetadata().get().getRef(), bill.getContent().get().getSource().getBytes()).get();
            if (value != null && !node.getTextContent().toLowerCase().contains(value.toLowerCase())) {
                return false;
            }
        }
        return true;
    }

    // Method to remove already present descriptions' results
    private List<AnalysisResultDescriptionGeneration> filterDescriptionGenerations(Element table, List<AnalysisResultDescriptionGeneration> newResults,
                                                                                   Bill bill) {
        NodeList rows = XercesUtils.getElementsByName(table, XmlHelper.TR);
        for (int i = 1; i < rows.getLength(); i++) {
            Node row = rows.item(i);
            if (isNotBlank(row)) {
                NodeList columns = XercesUtils.getElementsByName(row, XmlHelper.TD);
                for (int index = 0; index < newResults.size(); index++) {
                    AnalysisResultDescriptionGeneration newResult = newResults.get(index);
                    if (columns.getLength() > 3
                            && doesContainsRefs(columns.item(0), newResult.getEId(), bill)
                            && doesContainsValue(columns.item(1), newResult.getDescription())
                            && doesContainsValues(columns.item(2), newResult.getActors())
                            && doesContainsValues(columns.item(3), newResult.getHigh_level_process())) {
                        newResults.remove(index);
                        index--;
                    }
                }
            }
        }
        return newResults;
    }

    // Method to add descriptions' results in XML
    private void addPrefillTextInTableDescriptionGenerations(Element table, List<AnalysisResultDescriptionGeneration> newResults, Bill bill, String lfdsRef) {
        List<AnalysisResultDescriptionGeneration> results = filterDescriptionGenerations(table, newResults, bill);
        NodeList rows = XercesUtils.getElementsByName(table,XmlHelper.TR);
        int resultIndex = 0;
        for (int i = 1; i < rows.getLength(); i++) {
            if (resultIndex >= results.size()) break;
            Node row = rows.item(i);
            if (isBlank(row)) {
                NodeList columns = XercesUtils.getElementsByName(row, XmlHelper.TD);
                AnalysisResultDescriptionGeneration result = results.get(resultIndex);
                insertIdsInNthColumn(row, columns, 0, result.getEId(), bill, lfdsRef);
                insertValueInNthColumn(row, columns, 1, result.getDescription());
                insertValuesInNthColumn(row, columns, 2, result.getActors());
                insertValuesInNthColumn(row, columns, 3, result.getHigh_level_process());
                resultIndex++;
            }
        }
        for (int i = resultIndex; i < results.size(); i++) {
            AnalysisResultDescriptionGeneration result = results.get(i);
            Node trElt = table.getOwnerDocument().createElement(XmlHelper.TR);
            XercesUtils.addAttribute(trElt, XMLID, IdGenerator.generateId());
            appendRefsInNewColumn(trElt, result.getEId(), bill, lfdsRef);
            appendValueNewColumn(trElt, result.getDescription());
            appendValuesNewColumn(trElt, result.getActors());
            appendValuesNewColumn(trElt, result.getHigh_level_process());
            table.appendChild(trElt);
        }
    }

