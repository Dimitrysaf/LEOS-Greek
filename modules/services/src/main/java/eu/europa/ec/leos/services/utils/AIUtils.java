    // Method to remove already present data flows' results
    private List<AnalysisResultDataFlowsGeneration> filterFlowsGenerations(Node table, List<AnalysisResultDataFlowsGeneration> newResults, Bill bill) {
        NodeList rows = XercesUtils.getElementsByName(table,XmlHelper.TR);
        for (int i=1; i<rows.getLength(); i++) { // Skipping header
            Node row = rows.item(i);
            if (isNotBlank(row)) {
                NodeList columns = XercesUtils.getElementsByName(row,XmlHelper.TD);
                for (int index=0; index<newResults.size(); index++) {
                    AnalysisResultDataFlowsGeneration newResult = newResults.get(index);
                    if (columns.getLength() > 4
                            && doesContainsRefs(columns.item(1), newResult.getEId(), bill)
                            && doesContainsValue(columns.item(2), newResult.getAddresser())
                            && doesContainsValue(columns.item(3), newResult.getAddressee())
                            && doesContainsValue(columns.item(4), newResult.getAction_result())) {
                        newResults.remove(index);
                        index--;
                    }
                }
            }
        }
        return newResults;
    }

    private void addPrefillTextInTableFlowsGenerations(Node table, List<AnalysisResultDataFlowsGeneration> newResults, Bill bill, String lfdsRef) {
        List<AnalysisResultDataFlowsGeneration> results = this.filterFlowsGenerations(table, newResults, bill);
        NodeList rows = XercesUtils.getElementsByName(table,XmlHelper.TR);
        int resultIndex = 0;
        for (int i=1; i<rows.getLength(); i++) { // Skipping header
            if (resultIndex >= results.size()) break;
            Node row = rows.item(i);
            if (isBlank(row)) {
                NodeList columns = XercesUtils.getElementsByName(row,XmlHelper.TD);
                AnalysisResultDataFlowsGeneration result = results.get(resultIndex);
                insertValueInNthColumn(row, columns, 0, " ");
                insertIdsInNthColumn(row, columns, 1, result.getEId(), bill, lfdsRef);
                insertValueInNthColumn(row, columns, 2, result.getAddresser());
                insertValueInNthColumn(row, columns, 3, result.getAddressee());
                insertValueInNthColumn(row, columns, 4, result.getAction_result());
                insertValueInNthColumn(row, columns, 5, " ");
                resultIndex++;
            }
        }
        for (int i = resultIndex; i < results.size(); i++) {
            AnalysisResultDataFlowsGeneration result = results.get(i);
            Node trElt = table.getOwnerDocument().createElement(XmlHelper.TR);
            XercesUtils.addAttribute(trElt, XMLID, IdGenerator.generateId());
            appendValueNewColumn(trElt, " ");
            appendRefsInNewColumn(trElt, result.getEId(), bill, lfdsRef);
            appendValueNewColumn(trElt, result.getAddresser());
            appendValueNewColumn(trElt, result.getAddressee());
            appendValueNewColumn(trElt, result.getAction_result());
            appendValueNewColumn(trElt, " ");
            table.appendChild(trElt);
        }
    }

    // Method to find specific table in XML
    private Element findNthTableInLevel(Document doc, String levelNumber, int n) {
        // Find correct level thanks to numbering
        String xpath = "//akn:" + XmlHelper.NUM + "[text()='" + levelNumber + "']";
        NodeList levelNums = XercesUtils.getElementsByXPath(doc, xpath);
        if (levelNums.getLength() > 0) {
            Node levelNum = levelNums.item(0);
            NodeList tables = XercesUtils.getElementsByName(levelNum.getParentNode(), XmlHelper.TABLE);
            if (tables.getLength() > n) {
                return (Element) tables.item(n);
            }
        }
        return null;
    }

    // Main method to insert AI track changes in XML
    public byte[] insertPrefillElementsInXml(AnalysisResults data, byte[] xml, Bill bill, String lfdsRef) {
        if (data == null) {
            return xml;
        }
        Document doc = XercesUtils.createXercesDocument(xml, true);
        if (data.getDescGenerationResults() != null && !data.getDescGenerationResults().isEmpty()) {
            Element table = findNthTableInLevel(doc, "4.1.", 0);
            if (table != null) {
                addPrefillTextInTableDescriptionGenerations(table, data.getDescGenerationResults(), bill, lfdsRef);
            }
        }
        if (data.getDataGenerationResults() != null && !data.getDataGenerationResults().isEmpty()) {
            Element table = findNthTableInLevel(doc, "4.2.", 0);
            if (table != null) {
                addPrefillTextInTableDataGenerations(table, data.getDataGenerationResults(), bill, lfdsRef);
            }
        }
        if (data.getSolutionsGenerationResults() != null && !data.getSolutionsGenerationResults().isEmpty()) {
            Element table = findNthTableInLevel(doc, "4.3.", 0);
            if (table != null) {
                addPrefillTextInTableSolutionGenerations(table, data.getSolutionsGenerationResults(), bill, lfdsRef);
            }
        }
        if (data.getInterGenerationResults() != null && !data.getInterGenerationResults().isEmpty()) {
            Element table = findNthTableInLevel(doc, "4.4.", 0);
            if (table!=null) {
                this.addPrefillTextInTableInterGenerations(table, data.getInterGenerationResults(), bill, lfdsRef);
            }
            table = this.findNthTableInLevel(doc, "4.4.", 1);
            if (table!=null) {
                this.addPrefillTextInTableSubInterGenerations(table, data.getInterGenerationResults());
            }
        }
        if (data.getDataFlowsGenerationResults() != null && !data.getDataFlowsGenerationResults().isEmpty()) {
            Element table = findNthTableInLevel(doc, "4.2.", 1);
            if (table != null) {
                this.addPrefillTextInTableFlowsGenerations(table, data.getDataFlowsGenerationResults(), bill, lfdsRef);
            }
        }
        return XercesUtils.nodeToByteArray(doc);
    }

    private void appendNodeMref(Node node, String billRef, String id, String lfdsRef) {
        Node mrefNode = node.getOwnerDocument().createElement(MREF);
        XercesUtils.addAttribute(mrefNode, XMLID, IdGenerator.generateId());
        node.appendChild(mrefNode);
        Ref ref = new Ref(IdGenerator.generateId(), id, billRef, null);
        Result<String> result = this.referenceLabelService.generateLabel(Arrays.asList(ref), lfdsRef, XercesUtils.getId(node), node.getOwnerDocument(),
                true);
        XercesUtils.addContentToNode(mrefNode, result.get());
    }
